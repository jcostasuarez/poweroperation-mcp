/// Título del error Citect `code` (sin la base), si está en la tabla.
pub fn title(code: u32) -> Option<&'static str> {
    ERRORS.binary_search_by_key(&code, |e| e.0).ok().map(|i| ERRORS[i].1)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ordenada_y_conocidos() {
        assert!(ERRORS.windows(2).all(|w| w[0].0 < w[1].0));
        assert_eq!(title(424), Some("Tag not found"));
        assert_eq!(title(274), Some("Invalid argument passed"));
        assert_eq!(title(292), Some("Invalid function"));
        assert_eq!(title(99_999), None);
    }
}
